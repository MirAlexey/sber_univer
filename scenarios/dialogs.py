def _core_pairs(core: list[dict]) -> list[list[dict]]:
    """Разбивает чередующийся список реплик на пары (user, assistant)."""
    pairs: list[list[dict]] = []
    for msg in core:
        if msg["role"] == "user":
            pairs.append([msg])
        else:
            if pairs:
                pairs[-1].append(msg)
            else:
                pairs.append([msg])
    return pairs


def build_dialog(name: str, core: list[dict], target: int = USER_TURNS) -> list[dict]:
    """Собирает диалог: сюжетная канва, равномерно разбавленная отвлекающими блоками.

    Диалог заканчивается парой (благодарность, подтверждение профиля), так что
    итоговая история выглядит завершённой, а не оборванной на второстепенном вопросе.
    """
    pairs = _core_pairs(core)
    conclusion = CONCLUSIONS[name]
    need_distractors = max(0, target - len(pairs) - 1)

    # позиции вставки отвлечений: дробное равномерное распределение; коллизии
    # допустимы (несколько блоков подряд у одной пары выглядят естественно)
    positions: list[int] = []
    if need_distractors:
        for k in range(need_distractors):
            pos = int((k + 1) * len(pairs) / (need_distractors + 1))
            positions.append(min(pos, len(pairs) - 1))

    out: list[dict] = []
    di = 0
    cursor = 0
    for i, pair in enumerate(pairs):
        out.extend(pair)
        while cursor < len(positions) and positions[cursor] == i:
            d = DISTRACTORS[di % len(DISTRACTORS)]
            di += 1
            out.extend(d)
            cursor += 1

    out.extend(conclusion)
    return out


